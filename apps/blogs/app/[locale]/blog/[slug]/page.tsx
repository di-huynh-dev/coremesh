interface BlogPostPageProps {
  params: Promise<{ slug: string; locale: string }>;
}

// Only the locales a post exists in; /en/blog/<vi-only-slug> stays a 404.
export function generateStaticParams({ params }: { params: { locale: string } }) {
  return getAllPosts(isBlogLocale(params.locale) ? params.locale : "en").map((post) => ({
    slug: post.slug,
  }));
}

async function resolve(params: BlogPostPageProps["params"]) {
  const { slug, locale: rawLocale } = await params;
  setRequestLocale(rawLocale);
  const locale = isBlogLocale(rawLocale) ? rawLocale : "en";
  return { locale, post: getPostBySlug(slug, locale) };
}

export async function generateMetadata({
  params,
}: BlogPostPageProps): Promise<Metadata> {
  const { locale, post } = await resolve(params);
  if (!post) return { title: "Not found" };
  const tTopics = await getTranslations({ locale, namespace: "topics" });

  // The social image is generated by ./opengraph-image.tsx.
  return pageMetadata({
    locale,
    path: `/blog/${post.slug}`,
    title: post.title,
    description: post.excerpt,
    keywords: post.tags,
    available: postLocales(post.slug),
    ownImage: true,
    article: {
      publishedTime: post.date,
      modifiedTime: post.date,
      tags: post.tags,
      section: tTopics(`${post.topic}.title`),
    },
  });
}

function AdjacentLink({
  post,
  label,
  direction,
  locale,
}: {
  post?: BlogPostSummary;
  label: string;
  direction: "newer" | "older";
  locale: string;
}) {
  if (!post) return <div className="hidden sm:block" />;

  return (
    <Link
      href={`/${locale}/blog/${post.slug}`}
      className={`group flex flex-col gap-2 rounded-2xl border border-line p-5 transition-colors hover:border-ink/25 ${direction === "older" ? "sm:items-end sm:text-right" : ""}`}
    >
      <span className="inline-flex items-center gap-1.5 font-mono text-xs text-faint">
        {direction === "newer" ? <ArrowLeft className="size-3.5" /> : null}
        {label}
        {direction === "older" ? <ArrowRight className="size-3.5" /> : null}
      </span>
      <span className="font-semibold text-ink group-hover:text-cobalt">
        {post.title}
      </span>
    </Link>
  );
}

export default async function BlogPostPage({ params }: BlogPostPageProps) {
  const { locale, post } = await resolve(params);
  if (!post) notFound();

  const t = await getTranslations({ locale, namespace: "post" });
  const tTopics = await getTranslations({ locale, namespace: "topics" });
  const tLevels = await getTranslations({ locale, namespace: "levels" });
  const tCommon = await getTranslations({ locale, namespace: "common" });
  const tGuides = await getTranslations({ locale, namespace: "guides" });
  const { newer, older } = getAdjacentPosts(post.slug, locale);
  const { content, headings } = await renderMdx(post.body, mdxComponents, {
    anchorLabel: t("anchor"),
  });
  const related = getRelatedPosts(post, locale);
  const inSeries = getSeriesForPost(post.slug, locale);
  const nextInSeries = inSeries?.series.posts[inSeries.index + 1];

  const url = `${SITE_URL}/${locale}/blog/${post.slug}`;
  const topicTitle = tTopics(`${post.topic}.title`);
  const jsonLd = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "BlogPosting",
        "@id": `${url}#article`,
        url,
        mainEntityOfPage: { "@type": "WebPage", "@id": url },
        headline: post.title,
        description: post.excerpt,
        image: `${url}/opengraph-image`,
        // No separate "updated" field in meta.yaml yet: modified = published.
        datePublished: post.date,
        dateModified: post.date,
        inLanguage: contentLanguage[locale],
        author: authorJsonLd,
        publisher: authorJsonLd,
        isPartOf: { "@id": `${SITE_URL}/${locale}#website` },
        articleSection: topicTitle,
        keywords: post.tags,
        wordCount: post.content.split(/\s+/).length,
        timeRequired: `PT${post.readingTime}M`,
      },
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { name: t("breadcrumbHome"), item: `${SITE_URL}/${locale}` },
          { name: t("breadcrumbExplore"), item: `${SITE_URL}/${locale}/blog` },
          { name: topicTitle, item: `${SITE_URL}/${locale}/blog?topic=${post.topic}` },
          { name: post.title },
        ].map((crumb, index) => ({ "@type": "ListItem", position: index + 1, ...crumb })),
      },
    ],
  };

  return (
    <>
      <ReadingProgress targetId="article-body" slug={post.slug} />
      <ResumePrompt targetId="article-body" slug={post.slug} />
      <MobileToc headings={headings} targetId="article-body" />
      <JsonLd data={jsonLd} />

      <article className="wrap pt-10 md:pt-14">
        <header className="max-w-3xl">
          <nav aria-label="Breadcrumb" className="font-mono text-xs text-faint">
            <Link href={`/${locale}`} className="hover:text-ink">
              {t("breadcrumbHome")}
            </Link>
            <span className="mx-2">/</span>
            <Link href={`/${locale}/blog`} className="hover:text-ink">
              {t("breadcrumbExplore")}
            </Link>
            <span className="mx-2">/</span>
            <Link
              href={`/${locale}/blog?topic=${post.topic}`}
              className="hover:text-ink"
            >
              {tTopics(`${post.topic}.title`)}
            </Link>
          </nav>

          <ViewTransition name={`post-title-${post.slug}`} share="post-title" default="none">
            <h1 className="mt-5 text-[2.1rem] leading-[1.15] font-bold tracking-[-0.035em] text-ink text-balance md:text-5xl">
              {post.title}
            </h1>
          </ViewTransition>
          <p className="mt-5 text-lg leading-8 text-soft md:text-xl md:leading-9">
            {post.excerpt}
          </p>

          <div className="mt-8 flex flex-col gap-5 border-y border-line py-5 sm:flex-row sm:items-center sm:justify-between">
            <div className="flex items-center gap-3">
              <Image
                src={AUTHOR.avatar}
                alt=""
                width={44}
                height={44}
                className="size-11 rounded-full border border-line object-cover"
              />
              <div className="text-sm">
                <p className="font-semibold text-ink">{AUTHOR.name}</p>
                <p className="flex flex-wrap gap-x-2 text-soft">
                  <span>
                    {t("publishedOn")}{" "}
                    <time dateTime={post.date}>
                      {formatPostDate(post.date, locale, "long")}
                    </time>
                  </span>
                  <span aria-hidden>·</span>
                  <span>{tCommon("minRead", { minutes: post.readingTime })}</span>
                  {post.level ? (
                    <>
                      <span aria-hidden>·</span>
                      <span>{tLevels(post.level)}</span>
                    </>
                  ) : null}
                </p>
              </div>
            </div>
            <PostActions slug={post.slug} title={post.title} content={post.content} />
          </div>
        </header>

        <div className="mt-10 grid gap-12 lg:grid-cols-[minmax(0,720px)_minmax(0,1fr)] lg:gap-16">
          <div className="min-w-0">
            {inSeries ? (
              <SeriesBox
                id={inSeries.series.id}
                title={inSeries.series.title}
                topic={inSeries.series.topic}
                posts={inSeries.series.posts}
                index={inSeries.index}
              />
            ) : null}
            <div id="article-body" className="article-body">
              {content}
            </div>
            <CodeCopy targetId="article-body" label={tGuides("copy")} copiedLabel={tGuides("copied")} />
            <HeadingAnchors targetId="article-body" copiedLabel={t("anchorCopied")} />

            <footer className="mt-14 space-y-10">
              {inSeries ? (
                <div
                  className="rounded-2xl border border-line p-6"
                  style={topicAccent(inSeries.series.topic)}
                >
                  <p className="eyebrow before:bg-[var(--accent)]">
                    {nextInSeries
                      ? t("series.next")
                      : t("series.eyebrow", {
                          n: inSeries.index + 1,
                          total: inSeries.series.posts.length,
                        })}
                  </p>
                  {nextInSeries ? (
                    <Link
                      href={`/${locale}/blog/${nextInSeries.slug}`}
                      className="group mt-3 flex items-start justify-between gap-4"
                    >
                      <span>
                        <span className="font-mono text-xs text-faint">
                          {inSeries.index + 2}/{inSeries.series.posts.length} ·{" "}
                          {tCommon("minRead", { minutes: nextInSeries.readingTime })}
                        </span>
                        <span className="mt-1 block text-lg font-semibold tracking-[-0.01em] text-ink transition-colors group-hover:text-[var(--accent)]">
                          {nextInSeries.title}
                        </span>
                      </span>
                      <ArrowRight className="btn-arrow mt-6 size-5 shrink-0 text-[var(--accent)] transition-transform group-hover:translate-x-1" />
                    </Link>
                  ) : (
                    <p className="mt-3 leading-7 text-soft">{t("series.last")}</p>
                  )}
                  <Link
                    href={`/${locale}/series/${inSeries.series.id}`}
                    className="arrow-link mt-4 text-[var(--accent)]"
                  >
                    {inSeries.series.title}
                  </Link>
                </div>
              ) : null}

              {post.tags.length > 0 ? (
                <div className="flex flex-wrap items-center gap-2">
                  <span className="eyebrow mr-2">{t("tags")}</span>
                  {post.tags.map((tag) => (
                    <Link
                      key={tag}
                      href={`/${locale}/blog?q=${encodeURIComponent(tag)}`}
                      className="rounded-full border border-line px-3 py-1 font-mono text-xs text-soft transition-colors hover:border-ink/30 hover:text-ink"
                    >
                      #{tag}
                    </Link>
                  ))}
                </div>
              ) : null}

              <div className="flex items-start gap-4 rounded-2xl bg-paper p-6">
                <Image
                  src={AUTHOR.avatar}
                  alt=""
                  width={56}
                  height={56}
                  className="size-14 shrink-0 rounded-full border border-line object-cover"
                />
                <div>
                  <p className="font-semibold text-ink">{AUTHOR.name}</p>
                  <p className="mt-1 text-sm leading-6 text-soft">
                    {t("authorBio")}
                  </p>
                </div>
              </div>

              <nav className="grid gap-4 sm:grid-cols-2" aria-label={t("related")}>
                <AdjacentLink post={newer} label={t("newer")} direction="newer" locale={locale} />
                <AdjacentLink post={older} label={t("older")} direction="older" locale={locale} />
              </nav>
            </footer>
          </div>

          <aside className="hidden lg:block">
            <div className="sticky top-24 space-y-8">
              <TableOfContents headings={headings} />
              <div className="border-t border-line pt-6">
                <TopicTag topic={post.topic} />
              </div>
            </div>
          </aside>
        </div>
      </article>

      {related.length > 0 ? (
        <section aria-labelledby="related-title" className="wrap pt-20">
          <div className="flex items-end justify-between border-b border-line pb-4">
            <h2
              id="related-title"
              className="text-2xl font-bold tracking-[-0.03em] text-ink"
            >
              {t("related")}
            </h2>
            <Link href={`/${locale}/blog`} className="arrow-link">
              {t("backToExplore")}
            </Link>
          </div>
          {related.map((item) => (
            <PostRow key={item.slug} post={item} />
          ))}
        </section>
      ) : null}
    </>
  );
}
